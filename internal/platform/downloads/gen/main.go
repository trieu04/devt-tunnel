// Command gen rewrites internal/platform/downloads/manifest_gen.go.
//
// It downloads every target asset of one cloudflared release and computes each
// file's SHA-256 and size itself. Hashes and sizes published in the release body
// or API are never used, so a tampered release page cannot inject a hash; the
// generated diff is reviewed like code.
//
//	go run ./internal/platform/downloads/gen [-version 2026.11.0] [-o path]
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"time"
)

type target struct {
	goos, goarch, asset, format, member string
}

// Targets follow the design: macOS ships as .tgz, Linux and Windows as raw files.
var targets = []target{
	{"darwin", "amd64", "cloudflared-darwin-amd64.tgz", "tgz", "cloudflared"},
	{"darwin", "arm64", "cloudflared-darwin-arm64.tgz", "tgz", "cloudflared"},
	{"linux", "amd64", "cloudflared-linux-amd64", "raw", ""},
	{"linux", "arm64", "cloudflared-linux-arm64", "raw", ""},
	{"windows", "amd64", "cloudflared-windows-amd64.exe", "raw", ""},
}

const (
	repo     = "cloudflare/cloudflared"
	maxAsset = 256 << 20
)

var versionPattern = regexp.MustCompile(`^[0-9]{1,9}(\.[0-9]{1,9}){1,3}$`)

type artifact struct {
	target
	url, sha string
	size     int64
}

func main() {
	version := flag.String("version", "", "cloudflared release tag (default: latest)")
	out := flag.String("o", "internal/platform/downloads/manifest_gen.go", "output file")
	flag.Parse()
	log.SetFlags(0)
	client := &http.Client{Timeout: 10 * time.Minute}
	ctx := context.Background()

	tag := *version
	path := "latest"
	if tag != "" {
		path = "tags/" + tag
	}
	var release struct {
		TagName string `json:"tag_name"`
		Assets  []struct {
			Name string `json:"name"`
		} `json:"assets"`
	}
	if err := getJSON(ctx, client, "https://api.github.com/repos/"+repo+"/releases/"+path, &release); err != nil {
		log.Fatalf("release: %v", err)
	}
	if tag != "" && release.TagName != tag {
		log.Fatalf("release tag %q, want %q", release.TagName, tag)
	}
	tag = release.TagName
	if !versionPattern.MatchString(tag) {
		log.Fatalf("release tag %q is not a dotted version", tag)
	}
	assets := map[string]bool{}
	for _, a := range release.Assets {
		assets[a.Name] = true
	}
	var list []artifact
	for _, t := range targets {
		if !assets[t.asset] {
			log.Fatalf("release %s has no asset %s", tag, t.asset)
		}
		url := "https://github.com/" + repo + "/releases/download/" + tag + "/" + t.asset
		log.Printf("downloading %s", url)
		data, err := get(ctx, client, url)
		if err != nil {
			log.Fatalf("%s: %v", t.asset, err)
		}
		if t.format == "tgz" {
			if err := checkMember(data, t.member); err != nil {
				log.Fatalf("%s: %v", t.asset, err)
			}
		}
		sum := sha256.Sum256(data)
		list = append(list, artifact{target: t, url: url, sha: hex.EncodeToString(sum[:]), size: int64(len(data))})
	}
	if err := os.WriteFile(*out, render(tag, list), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s for cloudflared %s", *out, tag)
}

func request(ctx context.Context, url string) (*http.Request, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "devt-tunnel-manifest")
	return req, nil
}

func getJSON(ctx context.Context, client *http.Client, url string, v any) error {
	data, err := get(ctx, client, url)
	if err != nil {
		return err
	}
	return json.Unmarshal(data, v)
}

func get(ctx context.Context, client *http.Client, url string) ([]byte, error) {
	req, err := request(ctx, url)
	if err != nil {
		return nil, err
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxAsset+1))
	if err != nil {
		return nil, err
	}
	if len(data) > maxAsset {
		return nil, errors.New("asset is unexpectedly large")
	}
	if resp.ContentLength >= 0 && int64(len(data)) != resp.ContentLength {
		return nil, errors.New("truncated download")
	}
	return data, nil
}

func checkMember(data []byte, member string) error {
	gz, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return err
	}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return fmt.Errorf("archive has no regular file %q", member)
		}
		if err != nil {
			return err
		}
		if h.Name == member && h.Typeflag == tar.TypeReg {
			return nil
		}
	}
}

func render(version string, list []artifact) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./internal/platform/downloads/gen; DO NOT EDIT.\n")
	b.WriteString("// Refresh with `task downloads:manifest`; review the diff like code.\n\n")
	b.WriteString("package downloads\n\n")
	fmt.Fprintf(&b, "// cloudflared %s from https://github.com/%s/releases.\n", version, repo)
	b.WriteString("var manifest = []Artifact{\n")
	for _, a := range list {
		fmt.Fprintf(&b, "\t{Tool: %q, Version: %q, GOOS: %q, GOARCH: %q,\n\t\tURL: %q,\n\t\tSHA256: %q, Size: %d, Format: %q, Member: %q},\n",
			"cloudflared", version, a.goos, a.goarch, a.url, a.sha, a.size, a.format, a.member)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("format: %v", err)
	}
	return src
}
